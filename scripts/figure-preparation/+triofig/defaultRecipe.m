function recipe = defaultRecipe(sceneId, candidateOutputRelativePath)
%DEFAULTRECIPE Return a syntactically complete v2 trio-figure recipe.

sceneId = char(string(sceneId));
candidateOutputRelativePath = strrep(char(string(candidateOutputRelativePath)), char(92), '/');
[~, figureId] = fileparts(candidateOutputRelativePath);

recipe = struct( ...
    'schemaVersion', 2, ...
    'sceneId', sceneId, ...
    'candidateOutputRelativePath', candidateOutputRelativePath, ...
    'input', struct( ...
        'mainCaptureRelativePath', ['main/' sceneId '.tiff'], ...
        'thorcamCaptureRelativePath', ['thorcam/' sceneId '.tif'], ...
        'validationCaptureRelativePath', ['validation/' sceneId '.tiff'], ...
        'runManifestRelativePath', 'algo_run/experiment_manifest.json', ...
        'workspaceRelativePath', ['algo_run/' sceneId '/workspace.mat'], ...
        'expectedGenerationId', 'unknown', ...
        'requiredWorkspaceVariables', {{ ...
            'average_rectified_global_image', ...
            'average_rectified_image', ...
            'config_json'}}), ...
    'reconstruction', struct( ...
        'availableRunRelativePath', 'algo_run', ...
        'manifestRecordedRunRelativePath', '', ...
        'stageId', ''), ...
    'cameraPreparation', struct( ...
        'thorcam', struct('rotationDegrees', -90, 'flipVertical', true, ...
            'downsampleFactor', 1), ...
        'validation', struct('rotationDegrees', -90, 'flipVertical', false, ...
            'downsampleFactor', 1), ...
        'downsampleInterpolation', 'bilinear', ...
        'antiAliasSigmaFormula', '1 / downsampleFactor / 2'), ...
    'registration', struct( ...
        'transformSource', 'automatic', ...
        'reference', 'average_rectified_global_image', ...
        'rotationStartDegrees', -2, ...
        'rotationStopDegrees', 2, ...
        'rotationStepDegrees', 0.25, ...
        'rotationInterpolation', 'bilinear', ...
        'maskInterpolation', 'nearest', ...
        'translationMethod', 'normxcorr2', ...
        'cropMode', 'intersection', ...
        'requireExpectedCrop', false, ...
        'crop', struct('rowStartOneBased', 1, 'columnStartOneBased', 1, ...
            'height', 1, 'width', 1), ...
        'savedTransforms', struct( ...
            'thorcamRotationDegrees', 0, 'thorcamTranslationXY', [0, 0], ...
            'validationRotationDegrees', 0, 'validationTranslationXY', [0, 0])), ...
    'presentation', struct( ...
        'upsampleFactor', 4, ...
        'upsampleInterpolation', 'nearest', ...
        'intensityMultipliers', struct('globalLocal', 1, 'thorcam', 1, 'validation', 1), ...
        'recoveryNote', '', ...
        'zoomRois', [ ...
            struct('id', 1, 'xZeroBased', 0, 'yZeroBased', 0, ...
                'width', 1, 'height', 1, 'color', 'orange'), ...
            struct('id', 2, 'xZeroBased', 1, 'yZeroBased', 1, ...
                'width', 1, 'height', 1, 'color', 'cyan')]), ...
    'calibration', struct( ...
        'thorcam', struct('pointPairs', struct('referenceXY', zeros(0, 2), ...
            'movingXY', zeros(0, 2))), ...
        'validation', struct('pointPairs', struct('referenceXY', zeros(0, 2), ...
            'movingXY', zeros(0, 2)))), ...
    'figure', struct( ...
        'id', figureId, ...
        'assetDirectoryFromWrapper', ['./' figureId], ...
        'mainWidthCm', 4.2, ...
        'zoomWidthCm', 2.0), ...
    'comparison', struct( ...
        'maximumAbsolutePixelDifference', 0, ...
        'requireExactCandidateMatchBeforePublish', false), ...
    'provenance', struct('sourceSnapshotDirectoryRelativePath', ''));
end
