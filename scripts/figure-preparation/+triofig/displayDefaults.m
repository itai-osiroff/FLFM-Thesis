function display = displayDefaults(method)
%DISPLAYDEFAULTS Return the schema-6 presentation.display block.
% 'window' (default) maps each role through an explicit black/white window.
% 'legacyMinMax' keeps the original shared min/max normalization plus gains.
% Every optional image operation (background, smoothing, gamma) is disabled.

if nargin < 1, method = 'window'; end
window = struct('black', 0, 'white', 1, 'auto', true, ...
    'lowPercentile', 0.5, 'highPercentile', 99.8);
processing = struct( ...
    'background', struct('enabled', false, 'method', 'gaussian', 'sigmaPixels', 50), ...
    'smoothing', struct('enabled', false, 'sigmaPixels', 1), ...
    'gamma', struct('enabled', false, 'value', 1));
display = struct( ...
    'method', method, ...
    'roles', struct('flfm', window, 'global', window, 'local', window, 'thorcam', window), ...
    'processing', struct('flfm', processing, 'thorcam', processing), ...
    'zoom', struct('mode', 'inherit', 'marker', true, ...
        'regions', [triofig.zoomRegionDefaults(1), triofig.zoomRegionDefaults(2)]));
end
